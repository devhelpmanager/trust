 * @param array  $info    Формат, опыт, зарплата, коротко о вакансии.
 * @param array  $tasks   Чем предстоит заниматься.
 * @param array  $reqs    Что ждём от кандидата.
 * @param array  $conds   Что предлагаем.
 */
$trust_vacancy = static function ( string $key, string $title, string $dept, array $info, array $tasks, array $reqs, array $conds ): array {
	$sections = array();
	foreach ( array_combine( Trust\Vacancies::DEFAULT_SECTIONS, array( $tasks, $reqs, $conds ) ) as $section => $items ) {
		$sections[] = array(
			'title' => $section,
			'items' => implode( "\n", $items ),
		);
	}

	return array(
		'key'    => $key,
		'title'  => $title,
		'terms'  => array( 'department' => array( $dept ) ),
		'fields' => array(
			'trust_open'       => 1,
			'trust_format'     => $info[0],
			'trust_experience' => $info[1],
			'trust_salary'     => $info[2],
			'trust_summary'    => $info[3],
			'trust_sections'   => $sections,
		),
	);
};

