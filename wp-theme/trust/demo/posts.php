$trust_day = static fn( int $days ): string => wp_date( 'Y-m-d H:i:s', time() - $days * DAY_IN_SECONDS );

/**
 * Текст статьи-заглушки: вступление и разделы H2.
 *
 * @param string $intro    Вступление.
 * @param array  $sections Заголовок H2 => абзац.
 */
$trust_text = static function ( string $intro, array $sections ): string {
	$html = '<!-- wp:paragraph --><p>' . $intro . '</p><!-- /wp:paragraph -->';
	foreach ( $sections as $title => $text ) {
		$html .= "\n\n" . '<!-- wp:heading --><h2 class="wp-block-heading">' . $title . '</h2><!-- /wp:heading -->';
		$html .= "\n\n" . '<!-- wp:paragraph --><p>' . $text . '</p><!-- /wp:paragraph -->';
	}
	return $html;
};

/**
 * Абзац, заголовок H2 и список в разметке блоков.
 */
$trust_p    = static fn( string $html ): string => "<!-- wp:paragraph -->\n<p>" . $html . "</p>\n<!-- /wp:paragraph -->";
$trust_h2   = static fn( string $title ): string => "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">" . $title . "</h2>\n<!-- /wp:heading -->";
$trust_list = static function ( array $items, bool $ordered = false ): string {
	$tag = $ordered ? 'ol' : 'ul';
	return '<!-- wp:list' . ( $ordered ? ' {"ordered":true}' : '' ) . " -->\n<" . $tag . ' class="wp-block-list">' . implode(
		'',
		array_map( static fn( string $item ): string => "<!-- wp:list-item -->\n<li>" . $item . "</li>\n<!-- /wp:list-item -->", $items )
	) . '</' . $tag . ">\n<!-- /wp:list -->";
};

