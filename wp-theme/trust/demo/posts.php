$trust_day = static fn( int $days ): string => wp_date( 'Y-m-d H:i:s', time() - $days * DAY_IN_SECONDS );

/**
 * Текст статьи-заглушки: вступление и разделы H2.
 *
 * @param string $intro    Вступление.
 * @param array  $sections Заголовок H2 => абзац.
 */
$trust_text = static function ( string $intro, array $sections ): string {
	$html = '<!-- wp:paragraph --><p>' . $intro . '</p><!-- /wp:paragraph -->';
	foreach ( $sections as $title => $text ) {
		$html .= "\n\n" . '<!-- wp:heading --><h2 class="wp-block-heading">' . $title . '</h2><!-- /wp:heading -->';
		$html .= "\n\n" . '<!-- wp:paragraph --><p>' . $text . '</p><!-- /wp:paragraph -->';
	}
	return $html;
};

